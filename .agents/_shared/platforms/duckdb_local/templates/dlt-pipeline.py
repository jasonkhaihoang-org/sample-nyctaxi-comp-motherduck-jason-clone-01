# Runs in the Studio-local intent venv with the vibedata-dlt-duckdb-studio distribution
# (vibedata.dlt.duckdb import package). NEVER put credentials or DESTINATION__*
# config in this file — setup_environment() resolves them, and source secrets
# come from the Domain's bound Secret Store.
#
# RUN CONTRACT — this file is executed only by the `generating-dlt-pipeline`
# skill: your next tool call after committing this file is
